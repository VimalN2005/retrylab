    @staticmethod
    def _extract_service_name(target: str) -> str:
        """Infer readable service name from target URL pattern."""
        lower = target.lower()
        if "stripe" in lower:
            return "Stripe Payments"
        if "openai" in lower:
            return "OpenAI LLM API"
        if "anthropic" in lower:
            return "Anthropic Claude"
        if "twilio" in lower:
            return "Twilio SMS/Voice"
        if "github" in lower:
            return "GitHub REST API"
        if "aws" in lower or "amazonaws" in lower:
            return "AWS Cloud API"
        if "sendgrid" in lower or "resend" in lower:
            return "Transactional Email"
        return target.split("://")[-1].split("/")[0]
